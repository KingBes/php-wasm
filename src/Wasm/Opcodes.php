    /**
     * 归一化 opcode 为字节序列。
     *
     * @param int|array<int> $opcode
     */
    public static function bytes(int|array $opcode): string
    {
        if (is_int($opcode)) {
            return chr($opcode & 0xFF);
        }
        $out = '';
        foreach ($opcode as $b) {
            $out .= chr($b & 0xFF);
        }

        return $out;
    }
